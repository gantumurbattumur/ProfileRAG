import { useEffect, useRef, useState } from "react";
import { ArrowRight, Loader2 } from "lucide-react";
import { chat } from "../api";

const PROMPTS = [
  "What are Gana's strongest technical skills?",
  "Tell me about Gana's AI projects",
  "What kind of roles is Gana looking for?",
];

const UNAVAILABLE =
  "The AI assistant is unavailable right now. Everything else on this page still works.";

// Render [text](url) markdown links from model answers.
function renderContent(content) {
  const linkRegex = /\[([^\]]+)\]\(([^)]+)\)/g;
  const parts = [];
  let lastIndex = 0;
  let match;

  while ((match = linkRegex.exec(content)) !== null) {
    if (match.index > lastIndex) parts.push(content.slice(lastIndex, match.index));
    const [, text, href] = match;
    parts.push(
      <a
        key={match.index}
        href={href}
        target={href.startsWith("/") ? "_self" : "_blank"}
        rel="noopener noreferrer"
        download={href.endsWith(".pdf")}
        className="font-medium hover:underline"
        style={{ color: "var(--accent)" }}
      >
        {text}
      </a>
    );
    lastIndex = match.index + match[0].length;
  }

  if (lastIndex < content.length) parts.push(content.slice(lastIndex));
  return parts;
}

export default function AskAI() {
  const [messages, setMessages] = useState([]);
  const [input, setInput] = useState("");
  const [loading, setLoading] = useState(false);
  const listRef = useRef(null);

  useEffect(() => {
    const el = listRef.current;
    if (el) el.scrollTo({ top: el.scrollHeight, behavior: "smooth" });
  }, [messages, loading]);

  const ask = async (text) => {
    const question = text.trim();
    if (!question || loading) return;

    const history = messages.slice(-6).map(({ role, content }) => ({ role, content }));
    setMessages((prev) => [...prev, { role: "user", content: question }]);
    setInput("");
    setLoading(true);

    try {
      const res = await chat(question, history);
      setMessages((prev) => [...prev, { role: "assistant", content: res.answer }]);
    } catch {
      setMessages((prev) => [...prev, { role: "assistant", content: UNAVAILABLE }]);
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="space-y-4">
      <p className="text-sm" style={{ color: "var(--text-secondary)" }}>
        Ask a question about my background. Answers are generated by a RAG system over my resume
        and project notes.
      </p>

      {messages.length > 0 && (
        <div
          ref={listRef}
          className="max-h-96 space-y-3 overflow-y-auto rounded-2xl p-4"
          style={{ backgroundColor: "var(--bg-secondary)", border: "1px solid var(--border)" }}
        >
          {messages.map((msg, idx) => (
            <div key={idx} className={`flex ${msg.role === "user" ? "justify-end" : "justify-start"}`}>
              <div
                className="max-w-[85%] whitespace-pre-wrap rounded-2xl px-4 py-2.5 text-sm leading-relaxed"
                style={
                  msg.role === "user"
                    ? { backgroundColor: "var(--accent)", color: "var(--text-primary)" }
                    : { backgroundColor: "var(--bg-primary)", color: "var(--text-primary)" }
                }
              >
                {msg.role === "assistant" ? renderContent(msg.content) : msg.content}
              </div>
            </div>
          ))}
          {loading && (
            <div className="flex items-center gap-2 text-sm" style={{ color: "var(--text-secondary)" }}>
              <Loader2 className="h-4 w-4 animate-spin" aria-hidden="true" />
              Thinking…
            </div>
          )}
        </div>
      )}

      <form
        onSubmit={(e) => {
          e.preventDefault();
          ask(input);
        }}
        className="flex items-center gap-2 rounded-full py-2 pl-5 pr-2"
        style={{ backgroundColor: "var(--bg-secondary)", border: "1px solid var(--border)" }}
      >
        <input
          type="text"
          value={input}
          onChange={(e) => setInput(e.target.value)}
          placeholder="Ask a question…"
          aria-label="Ask a question about Gana"
          disabled={loading}
          className="flex-1 bg-transparent py-1.5 text-sm outline-none"
          style={{ color: "var(--text-primary)" }}
        />
        <button
          type="submit"
          disabled={loading || !input.trim()}
          aria-label="Send question"
          className="flex h-9 w-9 items-center justify-center rounded-full transition disabled:opacity-40"
          style={{ backgroundColor: "var(--accent)", color: "var(--text-primary)" }}
        >
          <ArrowRight className="h-4 w-4" aria-hidden="true" />
        </button>
      </form>

      {messages.length === 0 && (
        <div className="flex flex-wrap gap-2">
          {PROMPTS.map((p) => (
            <button
              key={p}
              type="button"
              onClick={() => ask(p)}
              disabled={loading}
              className="rounded-full px-3 py-1.5 text-sm transition hover:opacity-80"
              style={{ backgroundColor: "var(--bg-secondary)", color: "var(--text-secondary)", border: "1px solid var(--border)" }}
            >
              {p}
            </button>
          ))}
        </div>
      )}
    </div>
  );
}
